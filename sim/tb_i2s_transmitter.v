`timescale 1ns / 1ps

module tb_i2s_transmitter;

    //-------------------------------------------------
    // Parameter
    //-------------------------------------------------
    parameter DATA_WIDTH = 16;

    // Simulation을 빠르게 하기 위해 작게 설정
    parameter BCLK_HALF_DIV = 4;


    //-------------------------------------------------
    // Testbench Signal
    //-------------------------------------------------
    reg clk;
    reg reset;

    reg signed [DATA_WIDTH-1:0] sample_in;

    wire sample_req;

    wire i2s_bck;
    wire i2s_lrck;
    wire i2s_dout;


    //-------------------------------------------------
    // DUT
    //-------------------------------------------------
    i2s_transmitter #(
        .DATA_WIDTH    (DATA_WIDTH),
        .BCLK_HALF_DIV (BCLK_HALF_DIV)
    ) dut (
        .clk        (clk),
        .reset      (reset),

        .sample_in  (sample_in),
        .sample_req (sample_req),

        .i2s_bck    (i2s_bck),
        .i2s_lrck   (i2s_lrck),
        .i2s_dout   (i2s_dout)
    );


    //-------------------------------------------------
    // 100 MHz Clock
    // Period = 10 ns
    //-------------------------------------------------
    initial begin
        clk = 1'b0;

        forever #5 clk = ~clk;
    end


    //-------------------------------------------------
    // Test
    //-------------------------------------------------
    initial begin

        //-------------------------------------------------
        // 초기값
        //-------------------------------------------------
        reset     = 1'b1;
        sample_in = 16'hA35C;

        #20;

        //-------------------------------------------------
        // Reset 해제
        //-------------------------------------------------
        reset = 1'b0;


        //-------------------------------------------------
        // 몇 Frame 기다림
        //-------------------------------------------------
        #3000;


        //-------------------------------------------------
        // 두 번째 PCM Sample
        //-------------------------------------------------
        sample_in = 16'h5AA5;

        #3000;


        //-------------------------------------------------
        // 세 번째 PCM Sample
        //-------------------------------------------------
        sample_in = 16'h1234;

        #3000;


        //-------------------------------------------------
        // Simulation 종료
        //-------------------------------------------------
        $finish;

    end

endmodule
